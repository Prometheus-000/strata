/**
 * STRATA → one readable file.
 *
 * A projection, like semantic.css and tokens.json — never a second copy. Run it
 * again rather than editing the output.
 *
 * The output is *source*, deliberately, because the thing this file gets handed
 * to is a reader. The built artifact in dist/ is one self-contained page and is
 * exactly the wrong thing to give a chat: it is a minified React bundle, so the
 * philosophy that justifies every value in it survives only as string literals
 * spliced between variable names. Recovering prose from one of those costs an
 * extraction script and loses every comment that was not a string.
 *
 *   node scripts/bundle.mjs           → strata.md   (the system: ~75KB)
 *   node scripts/bundle.mjs --full    → adds the showcase app (~145KB)
 */
import { readFileSync, writeFileSync, statSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, extname } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const full = process.argv.includes('--full')

const LANG = { '.ts': 'ts', '.tsx': 'tsx', '.css': 'css', '.json': 'json', '.md': 'markdown' }

/** Order is the reading order: why, then the contract, then the code. */
const SYSTEM = [
  ['README.md', 'What Strata is, and how to run it.'],
  ['GRAMMAR.md', 'Every rule with the reason that earned it. The most important file here.'],
  ['src/tokens/tokens.json', 'GENERATED. The machine-readable contract: seeds, their ranges, and the reason for each dial.'],
  ['src/tokens/primitives.css', 'Tier 1. Raw, context-free scales. Components never reference these.'],
  ['src/tokens/semantic.css', 'GENERATED from the engine. Tier 2 — the only vocabulary components may speak.'],
  ['src/theme/generateTheme.ts', 'THE ENGINE. Six seeds in, the whole semantic tier out, in OKLCH.'],
  ['src/theme/ledger.ts', 'THE LEDGER. Every generated token is a proposal; a cut one collapses to a declared fallback, never vanishes.'],
  ['src/theme/ledger.json', 'AUTHORED. What people decided about each token: proposed, kept, or cut — with a reason and a name.'],
  ['src/theme/color.ts', 'OKLCH ↔ sRGB and WCAG contrast, used for the live contrast receipts.'],
  ['src/theme/compilePrompt.ts', 'Prose → seeds, with a receipt per word. The phrase is the record.'],
  ['src/theme/imageSeeds.ts', 'An image → seeds, sampled in the browser.'],
  ['src/theme/ThemeContext.tsx', 'The React provider. A theme also fits in a URL hash.'],
  ['src/behavior/useTabs.ts', 'Layer 1. Roving tabindex and ARIA. Never forked.'],
  ['src/behavior/useDialog.ts', 'Layer 1. Native <dialog> lifecycle and backdrop dismissal.'],
  ['src/components/index.tsx', 'Layer 2. Twelve recipes, composed from Layer 0 + Layer 1.'],
  ['src/components/strata.css', 'Layer 2 styling. Speaks the semantic tier only — no literals.'],
]
const SHOWCASE = [
  ['src/site/App.tsx', 'The showcase page.'],
  ['src/site/ThemeLab.tsx', 'The Theme Lab — describe, sample, wander, keep.'],
  ['src/site/Console.tsx', 'Layer 3 example: a generation console built from the recipes.'],
  ['src/site/site.css', 'Showcase styling.'],
]

const files = full ? [...SYSTEM, ...SHOWCASE] : SYSTEM
const out = []

out.push(`# Strata — complete source bundle

A design system for AI product teams. Themes are data: six seeds
(\`hue\`, \`chroma\`, \`warmth\`, \`energy\`, \`density\`, \`appearance\`) derive every
colour, radius, rhythm and easing, in perceptually-uniform OKLCH.

**This file is a projection, not the source.** It is generated by
\`scripts/bundle.mjs\` and regenerated rather than edited — the same rule the
system applies to its own token files.

## How to read it

The architecture splits what a design system usually fuses, because meaning,
behaviour and expression have wildly different half-lives and governing all
three at the speed of the slowest is how a system becomes a cage:

| Layer | What it holds | Governance |
| --- | --- | --- |
| 0 · Meaning | semantic tokens, derived by the engine | strict · one author · never forked |
| 1 · Behaviour | focus, keyboard, ARIA | shared · never forked |
| 2 · Recipes | styled compositions of 0 + 1 | forkable by default |
| 3 · Local | feature-owned one-offs | free · promotion earned by reuse |

**The one rule that makes it a system:** a recipe never references a raw value.
It speaks the semantic tier, and the semantic tier has exactly one author — the
engine. \`src/tokens/semantic.css\` and \`src/tokens/tokens.json\` are compiled
output; changing a theme means changing seeds, never those files.

**The colour rule, stated once because it is the one most often broken:** an
arbitrary hue belongs to the *accent*. Neutrals move only on \`warmth\`, a bounded
paper ↔ slate axis at very low chroma. Flooding the neutrals with a free hue is
what turns a themed product into "the brown app".

## Contents

${files.map(([p, note], i) => `${i + 1}. \`${p}\` — ${note}`).join('\n')}

---
`)

let bytes = 0
for (const [path, note] of files) {
  const abs = join(root, path)
  const body = readFileSync(abs, 'utf8').replace(/\s+$/, '')
  bytes += statSync(abs).size
  const lang = LANG[extname(path)] ?? ''
  // README and GRAMMAR carry their own fenced blocks, and a three-backtick
  // wrapper around them closes at the first inner fence — which silently moves
  // where one file is understood to end and the next to begin. The wrapper has
  // to be longer than anything it contains.
  const longest = Math.max(0, ...(body.match(/^`{3,}/gm) ?? []).map((f) => f.length))
  const fence = '`'.repeat(Math.max(3, longest + 1))
  out.push(`\n## \`${path}\`\n\n${note}\n\n${fence}${lang}\n${body}\n${fence}\n`)
}

const text = out.join('')
writeFileSync(join(root, 'strata.md'), text)
console.log(
  `strata.md — ${files.length} files, ${(bytes / 1024).toFixed(0)}KB of source, ` +
  `${(text.length / 1024).toFixed(0)}KB out (~${Math.round(text.length / 4000)}k tokens)` +
  (full ? '' : '   [--full adds the showcase app]'),
)
